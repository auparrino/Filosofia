import re as _re

_B = r"(?<![\wàèéìòù'])"
_A = r"(?![\wàèéìòù])"


def _fix(wrong, bad, good):
    pat = _B + _re.escape(bad) + _A
    found = list(_re.finditer(pat, wrong))
    if len(found) != 1:
        raise ValueError("bad %r appears %d times in %r" % (bad, len(found), wrong))
    m = found[0]
    out = wrong[:m.start()] + good + wrong[m.end():]
    return _re.sub(r"\s+", " ", out).replace(" ,", ",").replace(" .", ".").strip()


