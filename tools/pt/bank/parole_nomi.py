"""Banco de sustantivos portugueses (PB) para hispanohablantes rioplatenses.

Cada entrada: (singular, género, plural, español, tema, nivel, nota)

Mismo esquema que el banco italiano (build_bank.py y banca.js lo leen así):
el tema usa las mismas claves que en italiano (casa, cibo, corpo, famiglia,
lavoro, città, negozi, viaggio, tempo, natura, animali, salute, tecnologia,
vestiti, sentimenti, sport, scuola, cultura, società, astratti) para que el
motor no cambie.

La nota es contrastiva: heterogenéricos (o leite, a árvore, a viagem),
heterotónicos (polícia, cérebro, nível), heterosemánticos o falsos amigos
(escritório, oficina, polvo, borracha, apelido) y plurales que traban
(-ões / -ães / -ãos, -is, -ns).

Se escriben seis campos por palabra (sin el tema, que da la sección) y el
plural se calcula con las reglas regulares cuando va vacío (""):

- vocal (también tónica o nasal -ã) → +s: casa / casas, café / cafés, irmã / irmãs;
- -m → -ns: homem / homens;
- -r, -z → +es: mulher / mulheres, luz / luzes;
- -al → -ais, -ol → -óis, -ul → -uis; -el → -éis si es aguda (hotel /
  hotéis) y -eis si ya lleva tilde (nível / níveis).

Los plurales en -ão, -il, -s, -x y -n se escriben siempre a mano (no hay
regla segura): _plural() se niega a adivinarlos.
"""
import re

_ACC = "áéíóúâêôãõà"


def _plural(s):
    last = s.split(" ")[0] if " " in s else s
    rest = s[len(last):]
    w = last
    if w.endswith("ão") or re.search(r"(il|s|x|n)$", w):
        raise ValueError("plural a mano: " + s)
    if re.search(r"[aeiouáéíóúâêôã]$", w):
        p = w + "s"
    elif w.endswith("m"):
        p = w[:-1] + "ns"
    elif re.search(r"[rz]$", w):
        p = w + "es"
    elif w.endswith("al"):
        p = w[:-2] + "ais"
    elif w.endswith("ol"):
        p = w[:-2] + "óis"
    elif w.endswith("ul"):
        p = w[:-2] + "uis"
    elif w.endswith("el"):
        p = w[:-2] + ("eis" if any(c in _ACC for c in w[:-2]) else "éis")
    else:
        raise ValueError("plural a mano: " + s)
    return p + rest


