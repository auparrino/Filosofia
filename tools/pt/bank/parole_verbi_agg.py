def _adj(m, f="", mp="", fp="", es="", lvl="", note=""):
    """The four forms; the regular ones are derived (-o, -e, -a, -z, -m, -ês)."""
    if not f:
        if m.endswith("o"):
            f = m[:-1] + "a"
        elif m.endswith("ês"):
            f = m[:-2] + "esa"
        elif m[-1] in "eaz" or m.endswith("m"):
            f = m
        else:
            raise ValueError("femenino a mano: " + m)
    if not mp:
        if m[-1] in "oea":
            mp = m + "s"
        elif m.endswith("ês"):
            mp = m[:-2] + "eses"
        elif m.endswith("z"):
            mp = m + "es"
        elif m.endswith("m"):
            mp = m[:-1] + "ns"
        else:
            raise ValueError("plural a mano: " + m)
    if not fp:
        fp = f + "s" if f != m else mp
    return (m, f, mp, fp, es, lvl, note)


