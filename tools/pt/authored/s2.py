# -*- coding: utf-8 -*-
"""Ejercicios de la estação 2 — Pé na Estrada (semanas 14-26, prefijo s2-).

Cada ítem nombra su semana («w») y la parte de la lección («part») a la que
corresponde.  Regla de oro: un ítem de la semana N solo usa tiempos con
TENSE_WEEK <= N (tools/curriculo.py).  La semana 26 (CHEFÃO) mezcla toda la
estación.

Los ids son s2-<semana>-<nn>, numerados en el orden en que aparecen en este
archivo: para no romperlos, agregá ítems nuevos al final de cada semana.
"""

TOPIC = {14: "gostar", 15: "imperfeito", 16: "pronomes", 17: "futuro",
         18: "condicional", 19: "comparativos", 20: "indefinidos",
         21: "perfeito_composto", 22: "passiva", 23: "subjuntivo",
         24: "conjuncoes", 25: "relativos", 26: "chefao_b1"}

P_CH = "Elegí la forma correcta."
P_CL = "Completá."
P_TR = "Traducí al portugués."
P_FX = "Encontrá el error: tocá lo que está mal y corregilo."
P_GD = "Mirá los tres ejemplos y completá el cuarto."
P_SC = "Leé las frases y descubrí la regla."
P_TY = "Escribí la forma."
P_CB = "Uní las frases en una sola usando el conector entre paréntesis."

_N = {}


def _base(w, part, typ, prompt, stem, answer, note, alt=None, **kw):
    _N[w] = _N.get(w, 0) + 1
    d = dict(id="s2-%d-%02d" % (w, _N[w]), w=w, part=part,
             level="A2" if w <= 16 else "B1", type=typ, topic=TOPIC[w],
             prompt=prompt, stem=stem, answer=answer, alt=list(alt or []),
             note=note)
    d.update(kw)
    return d


def ch(w, part, stem, options, answer, note, prompt=P_CH):
    return _base(w, part, "choice", prompt, stem, answer, note, options=options)


def cl(w, part, stem, answer, note, alt=None, prompt=P_CL):
    return _base(w, part, "cloze", prompt, stem, answer, note, alt)


def tr(w, part, stem, answer, alt, note):
    return _base(w, part, "translate", P_TR, stem, answer, note, alt)


def fx(w, part, stem, bad, good, cat, note):
    return _base(w, part, "fixerr", P_FX, stem, stem.replace(bad, good, 1), note,
                 bad=bad, good=good, cat=cat)


def gd(w, part, lead, stem, answer, trap, note, alt=None, prompt=P_GD):
    return _base(w, part, "garden", prompt, stem, answer, note, alt, lead=lead, trap=trap)


def sc(w, part, data, stem, options, answer, note):
    return _base(w, part, "scopri", P_SC, stem, answer, note, data=data, options=options)


def ty(w, part, prompt, stem, answer, note, alt=None):
    return _base(w, part, "typed", prompt, stem, answer, note, alt)


def cb(w, part, stem, answer, alt, note):
    return _base(w, part, "combina", P_CB, stem, answer, note, alt)


